"""Produce the admission evidence a compiled R0 dataset must carry.

Every check and every capability certificate is generated by a verification that
reads the actual artifacts, and records the hashes it was verified against, so a
reviewer can re-run the same check on the same bytes. Nothing here copies
capability names into a "passed" field.

Binding recorded on every evidence record:
  raw_capture_sha256   the raw native stream the samples came from
  raw_report_sha256    its capture report
  bundle_manifest_sha  the production bundle the capture was taken with
  capture_code_sha256  the capture entry that produced the stream
  contract_sha256      the current R0 interface contract
  dataset_manifest_sha the manifest being certified
  verification_scope   what was and was not verified
"""
